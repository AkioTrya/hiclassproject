CREATE TABLE IF NOT EXISTS course_schedules (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  day text NOT NULL CHECK (day IN ('Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Sabtu')),
  start_time time NOT NULL,
  end_time time NOT NULL,
  course_code text NOT NULL,
  name text NOT NULL,
  lecturer text NOT NULL,
  room text NOT NULL,
  class_group text NOT NULL CHECK (class_group IN ('A', 'B', 'Semua')),
  color text NOT NULL CHECK (color IN ('violet', 'blue', 'mint', 'peach', 'yellow')),
  credits smallint NOT NULL CHECK (credits BETWEEN 1 AND 6),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (start_time < end_time)
);

CREATE TABLE IF NOT EXISTS admin_login_attempts (
  ip_hash text PRIMARY KEY,
  attempts integer NOT NULL DEFAULT 0,
  window_started_at timestamptz NOT NULL DEFAULT now(),
  locked_until timestamptz
);

CREATE TABLE IF NOT EXISTS admin_audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action text NOT NULL CHECK (action IN ('create', 'update', 'delete')),
  schedule_id integer NOT NULL,
  schedule_data jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS course_schedules_day_start_idx
  ON course_schedules (day, start_time);

