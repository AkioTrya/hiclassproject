CREATE TABLE IF NOT EXISTS public.student_accounts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text NOT NULL UNIQUE CHECK (username ~ '^[a-z0-9][a-z0-9._-]{2,31}$'),
  password_hash text NOT NULL CHECK (length(password_hash) <= 200),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.student_tasks (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id integer NOT NULL REFERENCES public.student_accounts(id) ON DELETE CASCADE,
  title text NOT NULL CHECK (length(title) BETWEEN 1 AND 120),
  course_name text CHECK (course_name IS NULL OR length(course_name) <= 100),
  due_date date,
  completed boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.student_ebooks (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id integer NOT NULL REFERENCES public.student_accounts(id) ON DELETE CASCADE,
  title text NOT NULL CHECK (length(title) BETWEEN 1 AND 120),
  course_name text CHECK (course_name IS NULL OR length(course_name) <= 100),
  url text NOT NULL CHECK (length(url) BETWEEN 1 AND 2000),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS student_tasks_owner_due_idx
  ON public.student_tasks (user_id, due_date, created_at DESC);
CREATE INDEX IF NOT EXISTS student_ebooks_owner_created_idx
  ON public.student_ebooks (user_id, created_at DESC);

