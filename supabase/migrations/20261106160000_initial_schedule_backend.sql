CREATE OR REPLACE FUNCTION public.is_admin_login_locked(p_ip_hash text)
RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT COALESCE((
    SELECT locked_until > now()
    FROM public.admin_login_attempts
    WHERE ip_hash = p_ip_hash
  ), false);
$$;

CREATE OR REPLACE FUNCTION public.record_admin_login_failure(p_ip_hash text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  DELETE FROM public.admin_login_attempts
  WHERE window_started_at < now() - interval '1 day';

  INSERT INTO public.admin_login_attempts (ip_hash, attempts, window_started_at)
  VALUES (p_ip_hash, 1, now())
  ON CONFLICT (ip_hash) DO UPDATE SET
    attempts = CASE
      WHEN public.admin_login_attempts.window_started_at < now() - interval '15 minutes' THEN 1
      ELSE public.admin_login_attempts.attempts + 1
    END,
    window_started_at = CASE
      WHEN public.admin_login_attempts.window_started_at < now() - interval '15 minutes' THEN now()
      ELSE public.admin_login_attempts.window_started_at
    END,
    locked_until = CASE
      WHEN (
        CASE
          WHEN public.admin_login_attempts.window_started_at < now() - interval '15 minutes' THEN 1
          ELSE public.admin_login_attempts.attempts + 1
        END
      ) >= 5 THEN now() + interval '15 minutes'
      ELSE NULL
    END;
END;
$$;

CREATE OR REPLACE FUNCTION public.clear_admin_login_failures(p_ip_hash text)
RETURNS void
LANGUAGE sql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  DELETE FROM public.admin_login_attempts WHERE ip_hash = p_ip_hash;
$$;

CREATE OR REPLACE FUNCTION public.mutate_course_schedule(
  p_action text,
  p_schedule jsonb,
  p_allow_conflicts boolean DEFAULT false
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_id integer;
  v_day text;
  v_start time;
  v_end time;
  v_code text;
  v_name text;
  v_lecturer text;
  v_room text;
  v_group text;
  v_color text;
  v_credits smallint;
  v_record public.course_schedules%ROWTYPE;
  v_conflicts jsonb;
  v_schedule jsonb;
BEGIN
  IF p_action IS NULL OR p_action NOT IN ('create', 'update', 'delete') THEN
    RAISE EXCEPTION 'Unsupported schedule action';
  END IF;

  IF p_action = 'delete' THEN
    v_id := (p_schedule ->> 'id')::integer;
    SELECT * INTO v_record
    FROM public.course_schedules
    WHERE id = v_id
    FOR UPDATE;

    IF NOT FOUND THEN
      RETURN jsonb_build_object('error', 'not_found');
    END IF;

    PERFORM pg_advisory_xact_lock(hashtextextended(v_record.day, 0));
    DELETE FROM public.course_schedules WHERE id = v_id;
    INSERT INTO public.admin_audit_log (action, schedule_id, schedule_data)
    VALUES ('delete', v_id, to_jsonb(v_record));
    RETURN jsonb_build_object('deleted', true);
  END IF;

  v_day := p_schedule ->> 'day';
  v_start := (p_schedule ->> 'start')::time;
  v_end := (p_schedule ->> 'end')::time;
  v_code := p_schedule ->> 'code';
  v_name := p_schedule ->> 'name';
  v_lecturer := p_schedule ->> 'lecturer';
  v_room := p_schedule ->> 'room';
  v_group := p_schedule ->> 'group';
  v_color := p_schedule ->> 'color';
  v_credits := (p_schedule ->> 'credits')::smallint;
  PERFORM pg_advisory_xact_lock(hashtextextended(v_day, 0));

  SELECT COALESCE(
    jsonb_agg(jsonb_build_object(
      'id', id,
      'day', day,
      'start', to_char(start_time, 'HH24:MI'),
      'end', to_char(end_time, 'HH24:MI'),
      'code', course_code,
      'name', name,
      'lecturer', lecturer,
      'room', room,
      'group', class_group,
      'color', color,
      'credits', credits
    ) ORDER BY start_time),
    '[]'::jsonb
  )
  INTO v_conflicts
  FROM public.course_schedules
  WHERE day = v_day
    AND (p_action = 'create' OR id <> (p_schedule ->> 'id')::integer)
    AND start_time < v_end
    AND end_time > v_start
    AND (
      lower(room) = lower(v_room)
      OR lower(lecturer) = lower(v_lecturer)
      OR (class_group = v_group AND class_group <> 'Semua')
      OR class_group = 'Semua'
      OR v_group = 'Semua'
    );

  IF jsonb_array_length(v_conflicts) > 0 AND NOT p_allow_conflicts THEN
    RETURN jsonb_build_object('error', 'conflict', 'conflicts', v_conflicts);
  END IF;

  IF p_action = 'create' THEN
    INSERT INTO public.course_schedules (
      day, start_time, end_time, course_code, name, lecturer, room, class_group, color, credits
    ) VALUES (
      v_day, v_start, v_end, v_code, v_name, v_lecturer, v_room, v_group, v_color, v_credits
    )
    RETURNING * INTO v_record;
  ELSE
    v_id := (p_schedule ->> 'id')::integer;
    UPDATE public.course_schedules SET
      day = v_day,
      start_time = v_start,
      end_time = v_end,
      course_code = v_code,
      name = v_name,
      lecturer = v_lecturer,
      room = v_room,
      class_group = v_group,
      color = v_color,
      credits = v_credits,
      updated_at = now()
    WHERE id = v_id
    RETURNING * INTO v_record;

    IF NOT FOUND THEN
      RETURN jsonb_build_object('error', 'not_found');
    END IF;
  END IF;

  INSERT INTO public.admin_audit_log (action, schedule_id, schedule_data)
  VALUES (p_action, v_record.id, to_jsonb(v_record));

  v_schedule := jsonb_build_object(
    'id', v_record.id,
    'day', v_record.day,
    'start', to_char(v_record.start_time, 'HH24:MI'),
    'end', to_char(v_record.end_time, 'HH24:MI'),
    'code', v_record.course_code,
    'name', v_record.name,
    'lecturer', v_record.lecturer,
    'room', v_record.room,
    'group', v_record.class_group,
    'color', v_record.color,
    'credits', v_record.credits
  );
  RETURN jsonb_build_object('schedule', v_schedule);
END;
$$;

